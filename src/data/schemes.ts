export const getSchemeById = (id: string): Scheme | undefined => {
  return schemes.find(scheme => scheme.id === id);
};

export const getSchemesByRiskLevel = (riskLevel: Scheme['riskLevel']): Scheme[] => {
  return schemes.filter(scheme => scheme.riskLevel === riskLevel);
};

export const getSchemesWithTaxBenefit = (): Scheme[] => {
  return schemes.filter(scheme => scheme.taxBenefit.section80C || scheme.taxBenefit.section80CCD);
};

export const getSchemesByEligibility = (age: number, gender: 'male' | 'female' | 'other'): Scheme[] => {
  return schemes.filter(scheme => {
    const { minAge, maxAge, gender: schemeGender } = scheme.eligibility;

    const ageMatch = (minAge === null || age >= minAge) && (maxAge === null || age <= maxAge);
    const genderMatch = schemeGender === 'all' || schemeGender === gender ||
      (schemeGender === 'female' && gender === 'female');

    return ageMatch && genderMatch;
  });
};
